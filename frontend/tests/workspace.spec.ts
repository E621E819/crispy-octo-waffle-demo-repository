test('settings keeps the interface in Chinese and saves the display name', async ({ page }) => {
  await page.goto('/')
  await page.locator('.profile').click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toContainText('个人偏好')
  await expect(dialog).not.toContainText('English')
  await expect(dialog).not.toContainText('语言')
  await dialog.locator('#display-name').fill('中文用户')
  await dialog.getByRole('button', { name: '保存设置', exact: true }).click()
  await expect(page.getByRole('button', { name: '新建学习对话', exact: true })).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('lang', 'zh-CN')
  expect(await page.evaluate(() => localStorage.getItem('exam-radar-language'))).toBeNull()
  await page.reload()
  await expect(page.getByRole('button', { name: '新建学习对话', exact: true })).toBeVisible()
  await page.locator('.profile').click()
  await expect(page.getByRole('dialog').locator('#display-name')).toHaveValue('中文用户')
})
