test('practice updates mastery; editable packs export and share privately', async ({ page, browser }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '练习薄弱点', exact: true }).click()
  await expect(page.locator('.practice-card')).toBeVisible()
  await page.locator('.answer-option input').first().check()
  await page.getByRole('button', { name: '提交答案', exact: true }).click()
  await expect(page.locator('.feedback-score')).toContainText('掌握度')
  await page.getByText('查看参考答案', { exact: true }).click()
  await expect(page.locator('.feedback details[open]')).toBeVisible()
  await page.getByRole('button', { name: '复习资料', exact: true }).click()
  await page.getByRole('button', { name: '生成复习包', exact: true }).click()
  await expect(page.locator('.pack-card')).toHaveCount(1)
  await page.getByRole('button', { name: '编辑复习包', exact: true }).click()
  const editor = page.getByRole('textbox', { name: '编辑复习包 Markdown' })
  await editor.fill((await editor.inputValue()) + '\n\n## My study note\nKeep this revision note.')
  await page.locator('.artifact-save-row button').click()
  await expect(page.getByRole('status')).toContainText('修改已保存')
  const event = page.waitForEvent('download')
  await page.locator('.export-row').getByRole('button', { name: 'Word', exact: true }).click()
  const download = await event
  const bytes = await readFile((await download.path())!)
  expect(bytes.subarray(0, 2).toString()).toBe('PK')
  await page.getByRole('button', { name: '分享课程', exact: true }).click()
  await page.getByRole('button', { name: '创建分享链接', exact: true }).click()
  const link = await page.locator('#share-link').inputValue()
  const peer = await browser.newContext()
  const sharedPage = await peer.newPage()
  await sharedPage.goto(link)
  await expect(sharedPage.locator('.shared-main')).toContainText('Keep this revision note.')
  await expect(sharedPage.locator('.shared-main')).not.toContainText('预计掌握度')
  const token = new URL(link).searchParams.get('share')
  const payload = await (await sharedPage.request.get('/api/shared/' + token)).json()
  expect(JSON.stringify(payload)).not.toContain('"mastery"')
  expect(payload.sessions).toBeUndefined()
  await sharedPage.locator('#comment').fill('A useful revision pack.')
  await sharedPage.getByRole('button', { name: '发表评论', exact: true }).click()
  await expect(sharedPage.locator('.shared-discussion')).toContainText('A useful revision pack.')
  await peer.close()
})

test('create a real course without exam date and upload a source', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '新建课程', exact: true }).click()
  await page.locator('#course-name').fill('Browser QA course')
  await page.locator('#course-code').fill('QA101')
  await page.getByRole('dialog').getByRole('button', { name: '创建课程', exact: true }).click()
  await expect(page.locator('.dropzone')).toBeVisible()
  await page.locator('input[type=file]').setInputFiles({ name: 'notes.txt', mimeType: 'text/plain', buffer: Buffer.from('Chapter 1. Model evaluation. Precision equals true positives divided by predicted positives. Recall equals true positives divided by actual positives.') })
  await page.getByRole('button', { name: '上传资料', exact: true }).click()
  await expect(page.locator('.material-list')).toContainText('notes.txt')
  const health = await (await page.request.get('/api/health')).json()
  if (health.mode === 'demo') {
    await page.getByRole('button', { name: '分析课程', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('OPENAI_API_KEY')
  }
  await page.reload()
  await expect(page.locator('.course-list')).toContainText('Browser QA course')
})

