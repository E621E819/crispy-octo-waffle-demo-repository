test('course sources, map, conversation and exam DNA are usable', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await expect(page.locator('.model-badge')).toContainText('混合模式')
  await expect(page.locator('.model-badge svg')).toHaveCount(0)
  await page.locator('.source-chips button').first().click()
  await expect(page.locator('.source-text')).toContainText('[Page')
  await page.getByRole('button', { name: '关闭窗口' }).click()
  await page.locator('.nav-item').filter({ hasText: '知识地图' }).click()
  await expect(page.locator('.map-graph')).toBeVisible()
  await page.locator('.map-node').first().click()
  await expect(page.locator('.map-topic-detail')).toBeVisible()
  await page.getByRole('button', { name: 'Question DNA', exact: true }).click()
  await page.getByRole('button', { name: '分析历年卷', exact: true }).click()
  await expect(page.locator('.artifact-exam-years')).toHaveText('2024–2026')
  await expect(page.locator('.artifact-pattern-row')).toHaveCount(3)
  await page.getByRole('button', { name: /新建学习对话/ }).click()
  await page.getByRole('textbox', { name: '向 Exam Radar 提问' }).fill('Explain F1 score')
  await page.getByRole('button', { name: '发送消息', exact: true }).click()
  await expect(page.locator('.chat-message.assistant')).toBeVisible()
  await expect(page.locator('.chat-message.assistant')).toContainText('F1')
  expect(errors).toEqual([])
})

